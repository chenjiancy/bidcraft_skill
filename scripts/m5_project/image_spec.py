def fit_size(img_path, key, max_w=None, max_h=None):
    """等比缩放适配：返回 (宽cm, 高cm)。

    v2.0 统一等比口径（用户 2026-10-04 按成品标书确认）：
      - 除身份证外一律「宽=可用宽(16cm)、高按原图比例」——竖版扫描件自然占整页、
        横版按比例收缩，与成品标书一致；
      - 身份证保留固定框 8×5（小图特例；正反面左右并排属后续调整项）；
      - max_w/max_h 可再收紧（如表格内图）：先按可用宽定宽，超 max_h 时
        改按 max_h 定高、宽度随比例收缩。
    """
    spec = IMG_SPEC.get(key)
    if not spec:
        return None
    from PIL import Image
    with Image.open(img_path) as im:
        iw, ih = im.size
    if key == "身份证":
        box_w = float(spec.get("宽", 8))
        box_h = float(spec.get("高", 5))
        scale = min(box_w / iw, box_h / ih)
        return (round(iw * scale, 1), round(ih * scale, 1))
    w = float(PAGE["可用宽_cm"])
    if max_w:
        w = min(w, float(max_w))
    h = w * ih / iw
    if max_h and h > float(max_h):
        h = float(max_h)
        w = h * iw / ih
    return (round(w, 1), round(h, 1))
