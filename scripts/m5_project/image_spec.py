def fit_size(img_path, key, max_w=None, max_h=None):
    """等比缩放适配：返回 (宽cm, 高cm)。
    规则：竖版证书 23 高 × 16 宽；横版证书宽 16 高按比例；
    图片真实比例与口径框不一致时按 contain（宽高均不超出口径框）。
    """
    spec = IMG_SPEC.get(key)
    if not spec:
        return None
    from PIL import Image
    with Image.open(img_path) as im:
        iw, ih = im.size
    box_w = float(spec.get("宽", 16))
    box_h = spec.get("高", None)
    if box_h in ("自适应", None):
        return (box_w, box_w * ih / iw)
    scale = min(box_w / iw, float(box_h) / ih)
    return (round(iw * scale, 1), round(ih * scale, 1))
