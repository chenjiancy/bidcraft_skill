def _trim(doc):
    """删除空段（保留有文字/图片/分页的段），返回 doc。"""
    for p in list(doc.paragraphs):
        has_txt = any(r.text.strip() for r in p.runs)
        has_img = p._p.find(".//{http://schemas.openxmlformats.org/drawingml/2006/main}blip") is not None
        if not has_txt and not has_img:
            p._p.getparent().remove(p._p)
    return doc


def make_f09():
    """从承诺书.docx 裁剪「基本账户开户许可证承诺函」部分（前4段：标题/正文/附/图片），
    补落款段与图片占位段（人工标书 P74：落款投标人盖章 + 附开户许可证图）。"""
    src = os.path.join(HUMAN, "承诺书.docx")
    doc = Document(src)
    # 保留段[0]~[3]：标题、正文、附：、图片占位段；其后段全部删除
    keep = 4
    paras = list(doc.paragraphs)
    for p in paras[keep:]:
        p._p.getparent().remove(p._p)
    _trim(doc)
    # 补图片占位段（模板阶段占位，商务标填充时由 FILL_IMG_MAP 解析开户许可证图）
    img = doc.add_paragraph()
    img.add_run("【图片：基本账户开户许可证（或基本账户存款信息）扫描件】")
    # 补落款段（人工标书 P74 结构）
    sign = doc.add_paragraph()
    sign.add_run("投标人：【投标人名称】（盖单位公章）")
    out = os.path.join(OUT, "基本账户开户许可证承诺函_样本.docx")
    doc.save(out)
    return out


